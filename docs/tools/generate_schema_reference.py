"""Generates docs/reference/project-schema.md from the schema of a project file written by the
current build (so the reference always matches the code).

    PYTHONPATH=<build>/python python3 docs/tools/generate_schema_reference.py [--check] [output]

With ``--check`` the existing file is compared instead of written (exit status 1 when different).
"""
from __future__ import annotations

import sqlite3
import sys
import tempfile
from pathlib import Path

import openmine

HEADER = """# Project file schema reference

Generated by `docs/tools/generate_schema_reference.py` from a project written by the build
(`openmine.SCHEMA_VERSION` = {version}); the `schema_reference_up_to_date` test fails when it no
longer matches. The design rules (identifiers, deletion policies, migrations, integrity checks)
are explained in [database-schema.md](../architecture/database-schema.md) and the container in
[project-format.md](../architecture/project-format.md).

Column types are SQLite storage classes; `CHECK` constraints and table constraints are quoted
from the DDL. Foreign keys list the referenced table and the `ON DELETE` action.

"""


def describe(db: sqlite3.Connection) -> str:
    out = [HEADER.format(version=openmine.SCHEMA_VERSION)]
    tables = [r[0] for r in db.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name")]
    out.append(f"{len(tables)} tables: " + ", ".join(f"[`{t}`](#{t})" for t in tables) + ".\n")
    out.append(_er_diagram(db, tables))
    for t in tables:
        out.append(f"\n## {t}\n\n")
        ddl = db.execute("SELECT sql FROM sqlite_master WHERE type='table' AND name=?", (t,)).fetchone()[0]
        fks = {}
        for row in db.execute(f"PRAGMA foreign_key_list('{t}')"):
            # id, seq, table, from, to, on_update, on_delete, match
            fks[row[3]] = f"→ `{row[2]}`" + (f".{row[4]}" if row[4] else "") + f" ({row[6]})"
        out.append("| Column | Type | Null | Key / reference |\n|---|---|---|---|\n")
        for cid, name, ctype, notnull, default, pk in db.execute(f"PRAGMA table_info('{t}')"):
            key = "PK" if pk else ""
            if name in fks:
                key = (key + " " if key else "") + fks[name]
            out.append(f"| `{name}` | {ctype or ''} | {'NOT NULL' if notnull or pk else 'NULL'} | {key} |\n")
        checks = [c.strip() for c in _constraints(ddl)]
        if checks:
            out.append("\nConstraints: " + "; ".join(f"`{c}`" for c in checks) + "\n")
        idx = [r[0] for r in db.execute("SELECT sql FROM sqlite_master WHERE type='index' AND tbl_name=? AND sql IS NOT NULL ORDER BY name", (t,))]
        if idx:
            out.append("\nIndexes: " + "; ".join(f"`{i}`" for i in idx) + "\n")
    return "".join(out)


def _er_diagram(db: sqlite3.Connection, tables) -> str:
    """Mermaid ER diagram of every foreign key (child }o-- parent, labelled column and ON DELETE)."""
    lines = ["\n## Relationships\n\n",
             "Every foreign key: the child table on the left, the referenced table on the right, the "
             "column and its `ON DELETE` action as the label (`o|`: the reference may be null).\n\n",
             "```mermaid\nerDiagram\n"]
    for t in tables:
        nullable = {name: not notnull for _, name, _, notnull, _, _ in db.execute(f"PRAGMA table_info('{t}')")}
        for row in sorted(db.execute(f"PRAGMA foreign_key_list('{t}')"), key=lambda r: r[3]):
            parent, column, action = row[2], row[3], row[6]
            card = "o|" if nullable.get(column, False) else "||"
            lines.append(f'  {t} }}o--{card} {parent} : "{column} ({action})"\n')
    lines.append("```\n")
    return "".join(lines)


def _constraints(ddl: str):
    """CHECK and UNIQUE clauses of a CREATE TABLE statement (column and table level)."""
    found, depth, i = [], 0, 0
    upper = ddl.upper()
    while True:
        j = min([k for k in (upper.find("CHECK", i), upper.find("UNIQUE (", i), upper.find("UNIQUE(", i)) if k >= 0], default=-1)
        if j < 0:
            return found
        k = ddl.find("(", j)
        depth, m = 0, k
        while m < len(ddl):
            depth += ddl[m] == "("
            depth -= ddl[m] == ")"
            if depth == 0:
                break
            m += 1
        found.append(" ".join(ddl[j:m + 1].split()))
        i = m + 1


def main(argv) -> int:
    check = "--check" in argv
    args = [a for a in argv if a != "--check"]
    target = Path(args[0]) if args else Path(__file__).resolve().parents[1] / "reference" / "project-schema.md"
    with tempfile.TemporaryDirectory() as d:
        f = Path(d) / "schema.openmine"
        p = openmine.Project.new("Schema", start="2026-01-05")
        p.save(f)
        p.close()
        db = sqlite3.connect(f)
        text = describe(db)
        db.close()
    if check:
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            print(f"{target} is out of date: run {Path(__file__).name} to regenerate it", file=sys.stderr)
            return 1
        return 0
    target.write_text(text, encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
