"""Generates docs/reference/python-api.md from the ``openmine`` package (signatures and
docstrings), so the reference always matches the code.

    PYTHONPATH=<build>/python python3 docs/tools/generate_python_reference.py [--check] [output]
"""
from __future__ import annotations

import inspect
import sys
from pathlib import Path

import openmine
from openmine import _project, geology, geotech, formats, plugins, repository, survey

HEADER = """# Python API reference

Generated by `docs/tools/generate_python_reference.py` from the `openmine` package of the build
(version {version}); the `python_reference_up_to_date` test fails when it no longer matches. The
guide with worked examples is [python.md](../python.md).

Optional features of a build are listed in `openmine.FEATURES` ({features}); methods that need a
missing one raise `NotImplementedError`.

"""

NAMESPACES = [
    ("Project", _project.Project, "project = Project.new(name, start) / Project.open(path)"),
    ("project.documents", _project.Documents, None),
    ("project.cad", _project.Cad, None),
    ("project.solids", _project.Solids, None),
    ("project.design", _project.Design, None),
    ("project.scheduler", _project.Scheduler, None),
    ("project.survey", _project.Survey, None),
    ("project.geology", _project.Geology, None),
    ("project.geotech", _project.Geotech, None),
    ("project.formats", _project.Formats, None),
    ("project.crs", _project.Crs, None),
    ("project.reports", _project.Reports, None),
    ("Development", _project.Development, None),
    ("Activity", _project.Activity, None),
    ("ScheduleResult", _project.ScheduleResult, None),
    ("PointCloud", _project.PointCloud, None),
    ("plugins.Registry", plugins.Registry, None),
    ("plugins.NativePlugins", plugins.NativePlugins, None),
    ("repository.Repository", repository.Repository, None),
    ("repository.WorkingCopy", repository.WorkingCopy, None),
]
MODULES = [("openmine.survey", survey), ("openmine.geology", geology), ("openmine.geotech", geotech), ("openmine.formats", formats),
           ("openmine.plugins", plugins)]


def _doc(obj) -> str:
    d = inspect.getdoc(obj) or ""
    return d.strip()


def _sig(name, fn) -> str:
    try:
        s = str(inspect.signature(fn))
    except (TypeError, ValueError):
        s = "(…)"
    s = s.replace("(self, ", "(").replace("(self)", "()").replace("(cls, ", "(").replace("(cls)", "()")
    s = s.replace('"', "").replace("'", "")  # postponed (string) annotations
    return f"{name}{s}"


def _members(cls):
    for name, member in cls.__dict__.items():
        if name.startswith("_") and name not in ("__init__",):
            continue
        if name == "__init__" and cls.__module__.endswith("_project"):
            continue
        yield name, member


def describe() -> str:
    out = [HEADER.format(version=openmine.__version__, features=", ".join(f"`{k}`" for k in sorted(openmine.FEATURES)))]
    out.append("## Contents\n\n" + "\n".join(f"- [`{t}`](#{t.lower().replace('.', '')})" for t, _, _ in NAMESPACES) + "\n" +
               "\n".join(f"- [`{t}`](#{t.lower().replace('.', '')})" for t, _ in MODULES) + "\n")
    for title, cls, usage in NAMESPACES:
        out.append(f"\n## {title}\n\n")
        if usage:
            out.append(f"`{usage}`\n\n")
        if _doc(cls) and cls.__doc__:
            out.append(_doc(cls) + "\n\n")
        for name, member in _members(cls):
            if isinstance(member, property):
                out.append(f"### `{name}` *(property)*\n\n")
                if _doc(member.fget):
                    out.append(_doc(member.fget) + "\n\n")
                continue
            if isinstance(member, (classmethod, staticmethod)):
                member = member.__func__
            if not callable(member):
                continue
            if name == "import_point_cloud" and member is getattr(cls, "import_pointcloud", None):
                out.append("### `import_point_cloud`\n\nAlias of `import_pointcloud`.\n\n")
                continue
            out.append(f"### `{_sig(name, member)}`\n\n")
            if _doc(member):
                out.append(_doc(member) + "\n\n")
    for title, mod in MODULES:
        out.append(f"\n## {title}\n\n")
        if _doc(mod):
            out.append(_doc(mod) + "\n\n")
        for name, fn in sorted(vars(mod).items()):
            if name.startswith("_") or not inspect.isfunction(fn) or fn.__module__ != mod.__name__:
                continue
            out.append(f"### `{_sig(name, fn)}`\n\n")
            if _doc(fn):
                out.append(_doc(fn) + "\n\n")
    return "".join(out).rstrip() + "\n"


def undocumented() -> list:
    """Public members without a docstring (the reference must describe every one)."""
    missing = []
    for title, cls, _ in NAMESPACES:
        for name, member in _members(cls):
            f = member.fget if isinstance(member, property) else (member.__func__ if isinstance(member, (classmethod, staticmethod)) else member)
            if callable(f) and not inspect.getdoc(f):
                missing.append(f"{title}.{name}")
    for title, mod in MODULES:
        for name, fn in vars(mod).items():
            if not name.startswith("_") and inspect.isfunction(fn) and fn.__module__ == mod.__name__ and not inspect.getdoc(fn):
                missing.append(f"{title}.{name}")
    return missing


def main(argv) -> int:
    check = "--check" in argv
    missing = undocumented()
    if missing:
        print("Undocumented public API: " + ", ".join(missing), file=sys.stderr)
        return 1
    args = [a for a in argv if a != "--check"]
    target = Path(args[0]) if args else Path(__file__).resolve().parents[1] / "reference" / "python-api.md"
    text = describe()
    if check:
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            print(f"{target} is out of date: run {Path(__file__).name} to regenerate it", file=sys.stderr)
            return 1
        return 0
    target.write_text(text, encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
